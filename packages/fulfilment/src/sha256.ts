// SHA-256, synchronous and dependency-free (FIPS 180-4) — for the driver's phone (M19-FR-03 · OB-294).
//
// The phone's route session is synchronous by construction (it runs in a moving van with no signal and must never await
// anything), and the browser's own `crypto.subtle.digest` is asynchronous. Two things on the phone need a digest at the
// moment of capture, offline: the delivery code the customer reads out is checked against the salted digest head office
// sent with the stop, and a captured proof photo is fingerprinted so head office can prove the file it received is the
// one the phone took. Head office uses node's own `createHash` for the same arithmetic; a unit test holds the two equal.

