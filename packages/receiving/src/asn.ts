// --- dock scheduling ------------------------------------------------------------

export interface DockSlot {
  readonly slotId: string;
  readonly storeId: string;
  readonly dockId: string;
  /** ISO-8601 UTC. */
  readonly startsAt: string;
  readonly endsAt: string;
  readonly supplierId?: string;
  readonly poIds?: readonly string[];
  readonly status: 'booked' | 'arrived' | 'completed' | 'no_show' | 'cancelled';
}

export class DockConflictError extends Error {
  constructor(
    public readonly dockId: string,
    public readonly clashingSlotId: string,
  ) {
    super(
      `Dock "${dockId}" is already booked by slot "${clashingSlotId}" for that time — two lorries at one door is a queue, not a schedule`,
    );
    this.name = 'DockConflictError';
  }
}

/** Book a dock slot, refusing an overlap on the same door. */
export function bookDockSlot(slot: DockSlot, existing: readonly DockSlot[]): DockSlot {
  if (Date.parse(slot.endsAt) <= Date.parse(slot.startsAt)) {
    throw new DockConflictError(slot.dockId, '(invalid window)');
  }
  const clash = existing.find(
    (s) =>
      s.dockId === slot.dockId &&
      s.slotId !== slot.slotId &&
      s.status !== 'cancelled' &&
      s.status !== 'no_show' &&
      Date.parse(s.startsAt) < Date.parse(slot.endsAt) &&
      Date.parse(slot.startsAt) < Date.parse(s.endsAt),
  );
  if (clash) {
    throw new DockConflictError(slot.dockId, clash.slotId);
  }
  return slot;
}

