// ASN, direct-store-delivery, dock scheduling and handheld receiving (M07-FR-01).
//
// This is the handheld in the receiver's hand at the back door, and four things go
// wrong there that nothing downstream can fix:
//
//   1. THE DOUBLE SCAN. A case is scanned, the handheld hesitates, the receiver
//      scans again. Without a globally unique command id that is 48 units received
//      instead of 24 — and the error is invisible until a stock count months later.
//      So every scan carries an id and a repeat is a **no-op that says so** (§31.1).
//
//   2. THE CASE COUNTED AS ONE. A case of 24 scanned against a barcode the system
//      thinks is a single unit adds 1. Pack conversion is exact (M03-FR-02) or the
//      scan is refused; it is never guessed.
//
//   3. THE UNKNOWN BARCODE WAVED THROUGH. Under time pressure an unrecognised item
//      gets keyed in as "closest match". That is how a catalogue rots. An unknown
//      barcode goes to a **resolution queue** — the delivery continues, the item does
//      not silently become another item.
//
//   4. THE PRICE EDITED AT THE DOOR. A receiver can change quantities, conditions and
//      batches — that is their job. They can never change the agreed price, because
//      the whole three-way match depends on the PO price being the one that was
//      agreed, not the one that was convenient (§28).
//
// Direct-store-delivery — goods arriving with no purchase order — is legitimate
// (bread, milk, a supplier rep) and is the commonest route for goods to enter
// unaccounted. It gets a controlled path: allowed, but recorded as DSD, capped by
// value, and needing an approver above the receiver.
//
// Pure and deterministic: the timestamp is injected, there is no clock.

import type { Money } from '../../contracts/src/money';
import type { PackHierarchy } from '../../product/src/pack';
