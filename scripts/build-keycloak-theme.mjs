#!/usr/bin/env node
// Regenerate the identity server's sign-in theme from the ONE source of the owner's sign-in design (OB-18).
//
// ── Why this exists ─────────────────────────────────────────────────────────
//
// The owner approved one sign-in look (OB-18, 5 Oct 2026). It is implemented once, in
// `infra/pilot/demo-login/ui.ts`: `LOGIN_CSS` (the stylesheet) and `LOGIN_COPY` (every word, English and Tamil).
// The Keycloak login theme (`infra/keycloak/themes/sre/login/`, ADR-0019) must wear exactly that look. Copying the
// stylesheet by hand would let the two drift the first time somebody touches either one, so this script copies it
// mechanically:
//
//   • resources/css/sre-login.css — the block between the BEGIN/END markers is `LOGIN_CSS`, verbatim. Everything after
//     the END marker is the theme's own additions (the Keycloak-only classes and the 48 px tap-target lift) and is
//     kept as written.
//   • messages/messages_en.properties and messages_ta.properties — the block between the markers is every
//     `LOGIN_COPY` key as `sre.<key>`, in that language. Everything outside it (Keycloak's own message keys) is kept.
//
// `ui.ts` is TypeScript that imports other workspace TypeScript, so esbuild bundles it in memory (the same tool
// `scripts/build-service.mjs` uses) and the bundle is imported from a data URL — nothing is written to disk but the
// theme files.
//
// The theme script (resources/js/sre-login.js) is hand-written, not generated: `LOGIN_JS` switches language in the
// browser only (and remembers it in localStorage), while on Keycloak the language must be the SERVER's choice
// (`kc_locale`, through `locale.supported` / `l.url`) so that every message Keycloak itself renders is in that language.
//
// Usage:  node scripts/build-keycloak-theme.mjs          (rewrite the generated blocks)
//         node scripts/build-keycloak-theme.mjs --check  (exit 1 if any generated block is out of date)

import { build } from 'esbuild';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = join(ROOT, 'infra/pilot/demo-login/ui.ts');
const THEME = join(ROOT, 'infra/keycloak/themes/sre/login');
const CHECK = process.argv.includes('--check');

const CSS_BEGIN = '/* BEGIN OB-18 LOGIN_CSS: generated by scripts/build-keycloak-theme.mjs from infra/pilot/demo-login/ui.ts. Do not edit by hand. */';
const CSS_END = '/* END OB-18 LOGIN_CSS. Theme additions below this line are hand-written. */';
const MSG_BEGIN = '# BEGIN OB-18 words: generated by scripts/build-keycloak-theme.mjs from LOGIN_COPY in infra/pilot/demo-login/ui.ts. Do not edit by hand.';
const MSG_END = '# END OB-18 words. Keycloak message keys below this line are hand-written.';

/** Bundle ui.ts in memory and import it. */
async function loadDesign() {
  const result = await build({
    entryPoints: [SOURCE],
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: ['node22'],
    write: false,
    logLevel: 'silent',
  });
  const code = result.outputFiles[0].text;
  return import(`data:text/javascript;base64,${Buffer.from(code, 'utf8').toString('base64')}`);
}

/**
 * One value for a Keycloak message file. Keycloak passes every message through java.text.MessageFormat, so a single
 * quote must be doubled and a brace quoted; the .properties format then needs backslashes and line breaks escaped.
 */
function propertyValue(text) {
  const formatted = text.replace(/'/g, "''").replace(/[{}]/g, (c) => `'${c}'`);
  return formatted
    .replace(/\\/g, '\\\\')
    .replace(/\r?\n/g, '\\n')
    .replace(/^\s/, (c) => `\\${c}`);
}

/** Replace the generated block of `file` (or create the file with just the block), keeping everything else. */
function withBlock(file, begin, end, body) {
  const block = `${begin}\n${body}${body.endsWith('\n') ? '' : '\n'}${end}\n`;
  if (!existsSync(file)) return block;
  const current = readFileSync(file, 'utf8');
  const from = current.indexOf(begin);
  const to = current.indexOf(end);
  if (from === -1 || to === -1 || to < from) {
    throw new Error(`${relative(ROOT, file)}: the generated-block markers are missing or out of order.`);
  }
  return current.slice(0, from) + block + current.slice(to + end.length + 1);
}

const { LOGIN_CSS, LOGIN_COPY } = await loadDesign();

const outputs = new Map();
outputs.set(join(THEME, 'resources/css/sre-login.css'), withBlock(join(THEME, 'resources/css/sre-login.css'), CSS_BEGIN, CSS_END, LOGIN_CSS));
for (const lang of ['en', 'ta']) {
  const copy = LOGIN_COPY[lang];
  const lines = Object.keys(LOGIN_COPY.en).map((key) => `sre.${key}=${propertyValue(copy[key])}`);
  const file = join(THEME, `messages/messages_${lang}.properties`);
  outputs.set(file, withBlock(file, MSG_BEGIN, MSG_END, `${lines.join('\n')}\n`));
}

let stale = 0;
for (const [file, content] of outputs) {
  const current = existsSync(file) ? readFileSync(file, 'utf8') : '';
  if (current === content) continue;
  if (CHECK) {
    stale += 1;
    console.error(`out of date: ${relative(ROOT, file)} (run: pnpm run build:keycloak-theme)`);
  } else {
    writeFileSync(file, content, 'utf8');
    console.log(`wrote ${relative(ROOT, file)}`);
  }
}
if (CHECK && stale > 0) process.exit(1);
console.log(CHECK ? 'keycloak theme is up to date with ui.ts' : 'keycloak theme generated from ui.ts');
