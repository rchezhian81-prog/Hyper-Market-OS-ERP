#!/usr/bin/env node
// W3 · M36-FR-04 "documentation" · P-06: the office "Developer guide" page's data, GENERATED from the published contract
// `docs/api/openapi.json` — never written by hand, so the guide can never say something the API does not do.
//
//   node scripts/developer-docs.mjs            → writes apps/web-erp/web/developer-docs.bundle.js (a build output,
//                                                ignored like every *.bundle.js; it sets window.sreDeveloperDocs)
//
// `scripts/build-app.mjs web-erp` runs it on every build of the office pages, so the guide is always the contract the
// release carries. The file is a compact reading of each operation: its method and path, its API group, the permission it
// needs, whether it is idempotent (an Idempotency-Key header), the fields of its request and of its reply (top level, with
// their types), and the fields a reply shows only once. No example values and no secrets: the contract holds none.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const OPENAPI_FILE = join(ROOT, 'docs', 'api', 'openapi.json');
export const DOCS_DATA_FILE = join(ROOT, 'apps', 'web-erp', 'web', 'developer-docs.bundle.js');
const METHODS = ['get', 'post', 'put', 'patch', 'delete'];

/** A schema's top-level fields: name → type (a $ref is named by the schema it points to). */
function fieldsOf(schema, schemas, depth = 0) {
  if (schema === undefined || schema === null || depth > 3) return undefined;
  if (typeof schema.$ref === 'string') return fieldsOf(schemas[schema.$ref.split('/').at(-1)], schemas, depth + 1);
  if (schema.type !== 'object' || schema.properties === undefined) return undefined;
  const required = new Set(Array.isArray(schema.required) ? schema.required : []);
  return Object.entries(schema.properties).map(([name, p]) => ({
    name,
    type: typeof p?.$ref === 'string' ? p.$ref.split('/').at(-1) : Array.isArray(p?.type) ? p.type.join(' | ') : (p?.type ?? (p?.const !== undefined ? 'const' : 'any')),
    required: required.has(name),
  }));
}

/** The compact guide from an OpenAPI 3.1 document. Pure and deterministic (sorted by path, then method). */
export function developerDocs(openapi) {
  const schemas = openapi.components?.schemas ?? {};
  const operations = [];
  for (const path of Object.keys(openapi.paths ?? {}).sort()) {
    for (const method of METHODS) {
      const op = openapi.paths[path][method];
      if (op === undefined) continue;
      const success = Object.entries(op.responses ?? {}).find(([code]) => /^2\d\d$/.test(code));
      const replySchema = success?.[1]?.content?.['application/json']?.schema;
      const requestSchema = op.requestBody?.content?.['application/json']?.schema;
      operations.push({
        method: method.toUpperCase(), path, group: op.tags?.[0] ?? '', operationId: op.operationId ?? '',
        permission: op['x-permission'] ?? null, entitlement: op['x-entitlement'] ?? null, idempotent: op['x-idempotent'] === true,
        ...(typeof op.description === 'string' ? { description: op.description } : {}),
        params: (op.parameters ?? []).filter((p) => p.in === 'path' || p.in === 'query').map((p) => ({ name: p.name, in: p.in, required: p.required === true })),
        ...(requestSchema === undefined ? {} : { request: fieldsOf(requestSchema, schemas) ?? [] }),
        ...(success === undefined ? {} : { replyStatus: Number(success[0]), reply: fieldsOf(replySchema, schemas) ?? [] }),
        ...(Array.isArray(op['x-shown-once']) ? { shownOnce: op['x-shown-once'] } : {}),
      });
    }
  }
  return {
    title: openapi.info?.title ?? '', version: openapi.info?.version ?? '', about: openapi.info?.description ?? '',
    groups: (openapi.tags ?? []).map((g) => ({ name: g.name, description: g.description ?? '' })),
    operations, source: 'docs/api/openapi.json',
  };
}

export function writeDeveloperDocs() {
  const docs = developerDocs(JSON.parse(readFileSync(OPENAPI_FILE, 'utf8')));
  // A classic script setting one global — `<` escaped so no text in the contract can end the element early.
  writeFileSync(DOCS_DATA_FILE, `// Generated by scripts/developer-docs.mjs from docs/api/openapi.json — do not edit.\nwindow.sreDeveloperDocs = ${JSON.stringify(docs).replace(/</g, '\\u003c')};\n`, 'utf8');
  return docs;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const docs = writeDeveloperDocs();
  console.log(`developer guide: ${docs.operations.length} operations written to ${DOCS_DATA_FILE.replace(`${ROOT}/`, '')}`);
}
