// OB-510 (owner, 28 Oct 2026, in writing) · ADR-0031 (amended) · ADR-0019 — the customer's token is signed by OUR
// self-hosted identity server (Keycloak), in a CUSTOMER realm of each shop's own (`sre-<shop>-customers`). This fills the
// customer sign-in service's `CustomerSessionSigner` port. It mints nothing: every token it hands back was signed by the
// identity server, and it BELIEVES one only after head office's own checker (`verifyToken`, RS256 against the realm's
// published keys — the check the API makes on every call) accepts it.
//
// How a right code becomes the customer's token, on the private network only:
//   1. this service's own client in the customer realm (`sre-customer-sign-in`, confidential; its secret generated by the
//      identity server and given to this service from a file at deploy time — never in the repository) takes a service
//      token (`client_credentials`) whose only power is managing the CUSTOMER realm's users;
//   2. the customer's account is found — or made, once — under a product id derived from the shop and the number
//      (`customer-<hash>`): the identity server never holds the phone number, and the same number always lands on the same
//      customer;
//   3. a fresh random one-time secret is set on that account and exchanged AT ONCE for the customer's token (the password
//      grant, allowed for this one client only); the secret is held for those two calls in memory only, never logged or
//      kept, and the next sign-in replaces it — nobody can sign in with it, because nobody ever sees it;
//   4. the token is checked: the realm's signature, its issuer, our API's audience, the shop pinned, the customer's id.
// The staff realm is untouched: this client exists only in the customer realm, so it can never touch a member of staff.
//
// Off by itself until an SMS provider is approved (OB-222): with no SMS port nothing is ever sent, so no code can be right.

import { createHash, randomBytes } from 'node:crypto';
import { verifyToken, type PublicKeyring } from './token';
import type { CustomerSessionSigner } from './customer-sign-in';

/** The product-id prefix every customer carries — the API refuses a customer realm token naming anybody else. */
export const CUSTOMER_SUBJECT_PREFIX = 'customer-';
/** This service's client in each customer realm. */
export const CUSTOMER_SIGN_IN_CLIENT_ID = 'sre-customer-sign-in';

/** A shop's customer realm name, from its staff realm's (`sre-store` → `sre-store-customers`). */
export const customerRealmOf = (shopRealm: string): string => `${shopRealm}-customers`;

/** The product id of the customer with this number at this shop — the same every time, never the number itself. */
export function customerSubjectFor(tenantId: string, phoneNumber: string): string {
  return `${CUSTOMER_SUBJECT_PREFIX}${createHash('sha256').update(`sre-customer\u0000${tenantId}\u0000${phoneNumber}`).digest('hex').slice(0, 32)}`;
}

export interface KeycloakCustomerSignerSettings {
  /** The customer realm on the PRIVATE network (`http://idp:8080/auth/realms/sre-store-customers`) — calls go here. */
  readonly internalIssuer: string;
  /** The same realm as its tokens name it (`https://<address>/auth/realms/sre-store-customers`) — the `iss` checked. */
  readonly issuer: string;
  readonly clientId?: string;
  /** This service's client secret in the customer realm (read from a file at deploy time; never in code or logs). */
  readonly clientSecret: string;
  /** The ONE shop this realm signs for — the token's `tenant_id` must name it. */
  readonly tenantId: string;
  /** Our API's name in the tokens. */
  readonly audience: string;
  /** The realm's published keys (`jwksKeyring` over `<internalIssuer>/protocol/openid-connect/certs`). */
  readonly keyring: PublicKeyring & { refresh?: () => Promise<number> };
  readonly fetch: typeof globalThis.fetch;
  readonly now: () => number;
  /** The longest a token may live (seconds) — the same ceiling the API applies. */
  readonly maxLifetimeSeconds?: number;
  /** Injectable randomness (tests). */
  readonly oneTimeSecret?: () => string;
}

/** Why the identity server would not sign the customer in — the service turns any of these into a plain refusal. */
export class CustomerSignerError extends Error {
  constructor(readonly step: string, readonly status?: number) {
    super(`the customer realm refused at "${step}"${status === undefined ? '' : ` (${status})`}`);
    this.name = 'CustomerSignerError';
  }
}

const form = (fields: Record<string, string>): string => new URLSearchParams(fields).toString();

export function keycloakCustomerSigner(s: KeycloakCustomerSignerSettings): CustomerSessionSigner {
  const issuer = s.internalIssuer.replace(/\/+$/, '');
  const realm = /\/realms\/([^/?#]+)/.exec(issuer)?.[1];
  if (realm === undefined) throw new Error('the customer realm address must name its realm (…/realms/<realm>)');
  const adminBase = issuer.replace(`/realms/${realm}`, `/admin/realms/${realm}`);
  const clientId = s.clientId ?? CUSTOMER_SIGN_IN_CLIENT_ID;
  const tokenUrl = `${issuer}/protocol/openid-connect/token`;
  const oneTime = s.oneTimeSecret ?? (() => randomBytes(32).toString('base64url'));
  let service: { token: string; until: number } | undefined;

  const serviceToken = async (): Promise<string> => {
    if (service !== undefined && service.until > s.now()) return service.token;
    const res = await s.fetch(tokenUrl, { method: 'POST', headers: { 'content-type': 'application/x-www-form-urlencoded' }, body: form({ grant_type: 'client_credentials', client_id: clientId, client_secret: s.clientSecret }) });
    if (!res.ok) throw new CustomerSignerError('service sign-in', res.status);
    const body = await res.json() as { access_token?: unknown; expires_in?: unknown };
    if (typeof body.access_token !== 'string') throw new CustomerSignerError('service sign-in');
    const life = typeof body.expires_in === 'number' ? body.expires_in : 60;
    service = { token: body.access_token, until: s.now() + Math.max(0, life - 30) * 1000 };
    return service.token;
  };
  const admin = async (method: string, path: string, body?: unknown): Promise<Response> => s.fetch(`${adminBase}${path}`, {
    method, headers: { authorization: `Bearer ${await serviceToken()}`, accept: 'application/json', ...(body === undefined ? {} : { 'content-type': 'application/json' }) },
    ...(body === undefined ? {} : { body: JSON.stringify(body) }),
  });
  const findUser = async (username: string): Promise<{ id: string; enabled: boolean } | undefined> => {
    const res = await admin('GET', `/users?${new URLSearchParams({ username, exact: 'true', briefRepresentation: 'true' })}`);
    if (!res.ok) throw new CustomerSignerError('find the customer', res.status);
    const found = (await res.json() as { id?: unknown; username?: unknown; enabled?: unknown }[]).find((u) => u.username === username);
    return found === undefined || typeof found.id !== 'string' ? undefined : { id: found.id, enabled: found.enabled !== false };
  };

  return {
    name: `the self-hosted identity server's customer realm (${realm})`,
    signIn: async ({ tenantId, phoneNumber }) => {
      if (tenantId !== s.tenantId) throw new CustomerSignerError('this realm signs for another shop');
      const subject = customerSubjectFor(tenantId, phoneNumber);
      let user = await findUser(subject);
      if (user === undefined) {
        // Made once. The account carries the product id and nothing personal — no number, no name, no email.
        const made = await admin('POST', '/users', { username: subject, enabled: true, attributes: { sre_user_id: [subject] }, requiredActions: [] });
        if (made.status !== 201 && made.status !== 409) throw new CustomerSignerError('make the customer', made.status);
        user = await findUser(subject);
        if (user === undefined) throw new CustomerSignerError('make the customer');
      }
      if (!user.enabled) throw new CustomerSignerError('the customer\'s sign-in is switched off');
      // A fresh one-time secret, set and spent at once; never kept, never logged, replaced at the next sign-in.
      const secret = oneTime();
      const set = await admin('PUT', `/users/${encodeURIComponent(user.id)}/reset-password`, { type: 'password', value: secret, temporary: false });
      if (!set.ok) throw new CustomerSignerError('prepare the sign-in', set.status);
      const res = await s.fetch(tokenUrl, {
        method: 'POST', headers: { 'content-type': 'application/x-www-form-urlencoded' },
        body: form({ grant_type: 'password', client_id: clientId, client_secret: s.clientSecret, username: subject, password: secret, scope: 'openid' }),
      });
      if (!res.ok) throw new CustomerSignerError('sign the customer in', res.status);
      const body = await res.json() as { access_token?: unknown };
      if (typeof body.access_token !== 'string') throw new CustomerSignerError('sign the customer in');
      // Believe it only as the API will: the realm's signature, issuer, our audience, this shop, this customer.
      const policy = {
        algorithm: 'RS256' as const, secret: '', keyring: s.keyring, subjectClaim: 'sre_user_id', issuer: s.issuer, tenantId: s.tenantId,
        subjectPrefix: CUSTOMER_SUBJECT_PREFIX, audience: s.audience, ...(s.maxLifetimeSeconds === undefined ? {} : { maxLifetimeSeconds: s.maxLifetimeSeconds }),
      };
      let verdict = verifyToken(body.access_token, policy, s.now());
      if (!verdict.ok && verdict.refusedBecause === 'key_not_ours' && s.keyring.refresh !== undefined) {
        await s.keyring.refresh(); // the realm rotated its key since the last read
        verdict = verifyToken(body.access_token, policy, s.now());
      }
      if (!verdict.ok || verdict.principal?.userId !== subject) throw new CustomerSignerError(`check the token (${verdict.refusedBecause ?? 'another customer'})`);
      const exp = (JSON.parse(Buffer.from(body.access_token.split('.')[1]!, 'base64url').toString('utf8')) as { exp: number }).exp;
      return { token: body.access_token, subject, expiresAtMs: exp * 1000 };
    },
  };
}

/** What is missing for the Keycloak signer, in the operator's words; empty when it can be composed (or is not asked for). */
export function keycloakSignerSettingsProblems(env: Readonly<Record<string, string | undefined>>): string[] {
  if ((env['CUSTOMER_SIGN_IN_SIGNER'] ?? '').trim() === '') return [];
  if (env['CUSTOMER_SIGN_IN_SIGNER'] !== 'keycloak') return [`CUSTOMER_SIGN_IN_SIGNER must be "keycloak" (OB-510) or unset — "${env['CUSTOMER_SIGN_IN_SIGNER']}" is not a signer this product knows`];
  const need: ReadonlyArray<readonly [string, string]> = [
    ['CUSTOMER_REALM_ISSUER', "the customer realm's public address, as its tokens name it (https://<address>/auth/realms/sre-store-customers)"],
    ['CUSTOMER_REALM_INTERNAL_ISSUER', 'the same realm on the private network (http://idp:8080/auth/realms/sre-store-customers)'],
    ['CUSTOMER_SIGN_IN_CLIENT_SECRET_FILE', "a file holding this service's client secret in the customer realm (given by the administrator; never committed)"],
    ['IDP_AUDIENCE', "the API's name in the tokens (sre-retail-os-api)"],
  ];
  return need.filter(([k]) => (env[k] ?? '').trim() === '').map(([k, what]) => `${k} is not set — ${what}`);
}
